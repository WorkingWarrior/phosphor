#!/usr/bin/env python3
"""Export the owned mockup fonts, preserving Unicode and bit-7-left rows."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
fonts = json.loads((ROOT / 'design/themes/fonts.json').read_text())['fonts']
out = ['// Generated by design/themes/export_fonts.py. Do not edit.',
       '#pragma once', '#include "Vfd.h"', '#ifdef BOARD_TOUCH349',
       'namespace theme_fonts {', 'struct Glyph { uint32_t cp; uint8_t rows[8]; };']
for key in ('c64', 'amiga'):
    font = fonts[key]
    out.append(f'inline constexpr Glyph {key}_glyphs[] = {{')
    for glyph in sorted(font['glyphs'].values(), key=lambda g: int(g['cp'], 16)):
        assert len(glyph['rows']) == 8
        out.append('  { ' + glyph['cp'] + ', { ' + ', '.join(glyph['rows']) + ' } },')
    out += ['};', f'inline const uint8_t *{key}_rows(uint32_t cp)', '{',
            f'  for (const auto &g : {key}_glyphs) if (g.cp == cp) return g.rows;',
            '  return nullptr;', '}']
out += ['}  // namespace theme_fonts',
        'extern const vfd::Font C64_FONT, AMIGA_FONT;', '#endif', '']
(ROOT / 'firmware/src/boards/touch349/gadget/ThemeFonts.h').write_text('\n'.join(out))
