#!/bin/zsh
# Rebuilds firmware/.../gadget/RetroArtData.h from art.txt (previews land in out/).
cd "$(dirname $0)"
mkdir -p out
H=../../firmware/src/boards/touch349/gadget/RetroArtData.h
tmp=out/art.h; rm -f $tmp
grep -v '^#' art.txt | while read name machine src crop; do
  [ -z "$name" ] && continue
  python3 convert.py $machine $src $name out $tmp $crop || exit 1
done
{ echo '// Generated by design/retro-proto/build_art.sh from art.txt. Do not edit.'; echo '#pragma once'; echo; cat $tmp; } > $H
